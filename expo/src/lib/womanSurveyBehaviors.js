function setModelValueIfChanged(model, fieldName, nextValue) {
  const question = model?.getQuestionByName?.(fieldName);
  if (!question) return;
  if (!surveyValuesEqual(model.getValue(fieldName), nextValue)) {
    model.setValue(fieldName, nextValue);
  }
}

function getPanelQuestionValue(panel, fieldName) {
  const question = panel?.getQuestionByName?.(fieldName);
  return question?.value;
}

function setPanelQuestionValueIfChanged(panel, fieldName, nextValue) {
  const question = panel?.getQuestionByName?.(fieldName);
  if (!question) return;
  if (!surveyValuesEqual(question.value, nextValue)) {
    question.value = nextValue;
  }
}

function surveyValuesEqual(a, b) {
  if (a === b) return true;
  if (a && b && typeof a === "object" && typeof b === "object") {
    return JSON.stringify(a) === JSON.stringify(b);
  }
  return String(a ?? "") === String(b ?? "");
}

function nextReverseHouseholdLineNumber(baseValue, childOffset) {
  const base = toFiniteNumber(baseValue);
  const start = base === null ? 0 : Math.trunc(base);
  // Household line numbers are two-digit reverse counters. They continue
  // through zero and wrap, for example 02 -> 01 -> 00 -> 99 -> 98.
  const next = ((start - childOffset - 1) % 100 + 100) % 100;
  return String(next).padStart(2, "0");
}

let wqPregnancyRowIdSequence = 0;

function ensureWqPregnancyRowId(panel, panelIndex) {
  const question = panel?.getQuestionByName?.(WQ_PREGNANCY_ROW_ID_FIELD);
  if (!question) return "";
  const existing = String(question.value || "");
  if (existing) return existing;
  wqPregnancyRowIdSequence += 1;
  const rowId = `wq-pregnancy-${Date.now().toString(36)}-${panelIndex + 1}-${wqPregnancyRowIdSequence}`;
  question.value = rowId;
  return rowId;
}

function defaultMultipleTextMissingKeysToZero(value, keys = []) {
  if (!value || typeof value !== "object") return value;
  const hasAnyAnswer = keys.some((key) => String(value[key] ?? "") !== "");
  if (!hasAnyAnswer) return value;
  let changed = false;
  const nextValue = { ...value };
  for (const key of keys) {
    if (String(nextValue[key] ?? "") === "") {
      nextValue[key] = "00";
      changed = true;
    }
  }
  return changed ? nextValue : value;
}

function defaultCountsToZeroWhenNo(model, parentFieldName, childFieldNames = []) {
  if (Number(model?.getValue?.(parentFieldName)) !== 2) return;
  for (const childFieldName of childFieldNames) {
    setModelValueIfChanged(model, childFieldName, "00");
  }
}

